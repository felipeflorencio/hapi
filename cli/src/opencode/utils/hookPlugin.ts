import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { isAbsolute, join, relative } from 'node:path';
import { logger } from '@/ui/logger';
import { configuration } from '@/configuration';

const PLUGIN_FILENAME = 'hapi-hook.ts';
const PACKAGE_JSON_FILENAME = 'package.json';
const PLUGIN_PACKAGE = '@opencode-ai/plugin';
// Pinned to the major version HAPI has been validated against (opencode
// 1.14.x). Using '*' would let an unrelated registry change pull a moving
// target into a code-execution path (the plugin runtime executes inside
// opencode with the session hook URL + token in scope).
const PLUGIN_PACKAGE_VERSION = '^1.14.0';

function buildPluginSource(hookUrl: string, token: string): string {
    const escapedUrl = JSON.stringify(hookUrl);
    const escapedToken = JSON.stringify(token);

    return `// Generated by HAPI. Do not edit manually.

const DEFAULT_HOOK_URL = ${escapedUrl};
const DEFAULT_HOOK_TOKEN = ${escapedToken};
const HOOK_URL = process.env.HAPI_OPENCODE_HOOK_URL || DEFAULT_HOOK_URL;
const HOOK_TOKEN = process.env.HAPI_OPENCODE_HOOK_TOKEN || DEFAULT_HOOK_TOKEN;

// The vocabulary the HAPI launcher understands (opencodeLocalLauncher's
// handleHookEvent). opencode 1.x emits these names directly; opencode 2.x
// emits its own names and is translated into these below.
const EVENT_NAMES = new Set([
    'message.updated',
    'message.part.updated',
    'permission.updated',
    'permission.asked',
    'permission.replied',
    'session.created',
    'session.updated',
    'tool.execute.before',
    'tool.execute.after'
]);

function pickString(value) {
    return typeof value === 'string' && value.length > 0 ? value : null;
}

function extractSessionId(value) {
    if (!value || typeof value !== 'object') return null;
    const record = value;
    const direct = (
        pickString(record.sessionId)
        || pickString(record.sessionID)
        || pickString(record.session_id)
        || (record.session && pickString(record.session.id))
    );
    if (direct) return direct;
    if (record.part && typeof record.part === 'object') {
        const nested = extractSessionId(record.part);
        if (nested) return nested;
    }
    if (record.info && typeof record.info === 'object') {
        const nested = extractSessionId(record.info);
        if (nested) return nested;
    }
    return null;
}

function extractSessionIdFromEvent(eventName, payload) {
    const direct = extractSessionId(payload);
    if (direct) return direct;
    if (!payload || typeof payload !== 'object') return null;
    const record = payload;
    if (record.info && typeof record.info === 'object') {
        const fromInfo = extractSessionId(record.info);
        if (fromInfo) return fromInfo;
        if (eventName.startsWith('session.')) {
            return pickString(record.info.id);
        }
    }
    return null;
}

async function sendHook(eventName, payload, sessionId) {
    if (!HOOK_URL || !HOOK_TOKEN) {
        return;
    }

    const body = JSON.stringify({
        event: eventName,
        payload,
        sessionId
    });

    try {
        await fetch(HOOK_URL, {
            method: 'POST',
            headers: {
                'Content-Type': 'application/json',
                'x-hapi-hook-token': HOOK_TOKEN
            },
            body
        });
    } catch {
        // Ignore hook errors to avoid disrupting OpenCode
    }
}

async function emit(eventName, payload, sessionId) {
    if (!EVENT_NAMES.has(eventName)) {
        return;
    }
    await sendHook(eventName, payload, sessionId || extractSessionIdFromEvent(eventName, payload));
}

// -- opencode 2.x bridge --
//
// opencode 2.x rejects the 1.x plugin module shape outright (its loader wants
// a default export carrying an id plus a setup/effect function), and once
// loaded it speaks a different event vocabulary: names like
// 'session.text.delta' instead of 'message.part.updated', and a payload under
// 'data' instead of 'properties'. Translating here keeps the launcher's
// handleHookEvent - and the remote/ACP paths that share it - untouched.

// callID -> { name, input }. 'session.tool.success' and '.failed' carry only
// the callID, while the launcher needs a tool name to emit anything, so the
// name observed on '.called' (or '.input.started', which lands first) has to
// be carried forward.
const TOOL_CALLS = new Map();
const TOOL_CALLS_MAX = 512;

function rememberToolCall(callId, name, input) {
    if (!callId) return;
    if (TOOL_CALLS.size >= TOOL_CALLS_MAX) {
        // Bounded so a long session cannot grow this without limit; insertion
        // order makes the oldest entry the least likely to still be awaited.
        TOOL_CALLS.delete(TOOL_CALLS.keys().next().value);
    }
    const previous = TOOL_CALLS.get(callId) || {};
    TOOL_CALLS.set(callId, {
        name: name || previous.name || null,
        input: input !== undefined ? input : previous.input
    });
}

/** opencode 2.x spells some events 'session.next.<rest>'; the bus drops 'next.'. */
function canonicalV2Type(type) {
    return type.startsWith('session.next.') ? 'session.' + type.slice('session.next.'.length) : type;
}

/**
 * Translate one opencode 2.x event into zero or more launcher events.
 * Returns an array of [eventName, payload] pairs.
 */
function translateV2Event(type, data) {
    const canonical = canonicalV2Type(type);
    const info = data && typeof data.info === 'object' && data.info !== null ? data.info : data;

    if (canonical === 'session.created') {
        return [['session.created', { info }]];
    }
    if (canonical === 'session.updated' || canonical === 'session.renamed') {
        return [['session.updated', { info }]];
    }
    if (canonical === 'session.text.delta') {
        return [['message.part.updated', {
            part: { type: 'text', id: data.textID, messageID: data.assistantMessageID },
            delta: data.delta
        }]];
    }
    if (canonical === 'session.text.ended') {
        return [['message.part.updated', {
            part: {
                type: 'text',
                id: data.textID,
                messageID: data.assistantMessageID,
                ...(typeof data.text === 'string' ? { text: data.text } : {})
            }
        }]];
    }
    if (canonical === 'session.tool.input.started') {
        rememberToolCall(data.callID, data.name, undefined);
        return [];
    }
    if (canonical === 'session.tool.called') {
        rememberToolCall(data.callID, data.tool, data.input);
        return [['tool.execute.before', {
            tool: { id: data.callID, name: data.tool, input: data.input }
        }]];
    }
    if (canonical === 'session.tool.success' || canonical === 'session.tool.failed') {
        const remembered = TOOL_CALLS.get(data.callID) || {};
        TOOL_CALLS.delete(data.callID);
        const name = remembered.name;
        if (!name) {
            // The launcher drops nameless tool events, so sending one would
            // only cost a round trip.
            return [];
        }
        return [['tool.execute.after', {
            tool: { id: data.callID, name, input: remembered.input },
            ...(canonical === 'session.tool.failed'
                ? { error: data.error }
                : { output: data.result !== undefined ? data.result : data.structured, content: data.content })
        }]];
    }
    // permission.* already matches the launcher's vocabulary in both majors.
    if (EVENT_NAMES.has(canonical)) {
        return [[canonical, data]];
    }
    return [];
}

async function handleV2Event(event) {
    if (!event || typeof event.type !== 'string') {
        return;
    }
    const data = event.data && typeof event.data === 'object' ? event.data : {};
    const sessionId = pickString(data.sessionID)
        || (event.durable && pickString(event.durable.aggregateID))
        || null;
    for (const [name, payload] of translateV2Event(event.type, data)) {
        await emit(name, payload, sessionId);
    }
}

/**
 * opencode 1.x entry point. Kept alongside the 2.x default export so one
 * generated file serves both majors: the 1.x loader reads this named export
 * and ignores the default, the 2.x loader reads the default and ignores this.
 */
export const HapiHookPlugin = async () => {
    return {
        event: async ({ event }) => {
            if (!event || typeof event.type !== 'string') {
                return;
            }
            if (!EVENT_NAMES.has(event.type)) {
                return;
            }
            await emit(event.type, event.properties, null);
        }
    };
};

/** opencode 2.x entry point. */
export default {
    id: 'hapi-hook',
    setup: async (context) => {
        const subscribe = context && context.event && context.event.subscribe;
        if (typeof subscribe !== 'function') {
            // Older or newer context shape: stay inert rather than throwing.
            // A plugin that throws in setup is reported as a load failure on
            // every reconnect, and the storage scanner still carries messages.
            return;
        }

        // The argument is accepted but not honoured - every subscription
        // receives the full event stream - so filtering happens above.
        // Called on the object, not through the extracted reference, in case
        // the implementation depends on its receiver.
        const stream = context.event.subscribe();
        if (!stream || typeof stream[Symbol.asyncIterator] !== 'function') {
            return;
        }

        // Detached on purpose: setup is awaited by the loader, and consuming
        // the stream inline would never return.
        void (async () => {
            try {
                for await (const event of stream) {
                    await handleV2Event(event);
                }
            } catch {
                // Stream torn down with the server; nothing to recover.
            }
        })();
    }
};
`;
}

function resolvePluginDir(rootPath: string): string {
    return join(rootPath, 'plugins');
}

/**
 * `rootPath` is a HAPI-managed directory only when it lives under
 * `configuration.happyHomeDir` (the default `OPENCODE_CONFIG_DIR` we
 * synthesize per-session). If a user has exported `OPENCODE_CONFIG_DIR`
 * pointing at e.g. their own `~/.config/opencode`, we must not pollute it
 * with a placeholder `package.json`.
 */
function isHapiManagedDir(rootPath: string): boolean {
    const home = configuration.happyHomeDir;
    if (!home) {
        return false;
    }
    const rel = relative(home, rootPath);
    // `relative` returns a path that does NOT start with '..' and is not
    // absolute when rootPath is inside home. On Windows a cross-volume
    // input (e.g. home=`C:\\hapi`, rootPath=`D:\\…`) makes `relative`
    // return the absolute `D:\\…` verbatim — `startsWith('/')` would miss
    // that, so use `isAbsolute` which covers both POSIX `/` and win32
    // `<letter>:\\`.
    return rel !== '' && !rel.startsWith('..') && !isAbsolute(rel);
}

function hasDeclaredPluginPackage(packageJsonPath: string): boolean {
    try {
        const parsed = JSON.parse(readFileSync(packageJsonPath, 'utf-8')) as {
            dependencies?: Record<string, string>;
            devDependencies?: Record<string, string>;
        };
        return Boolean(parsed.dependencies?.[PLUGIN_PACKAGE] ?? parsed.devDependencies?.[PLUGIN_PACKAGE]);
    } catch {
        return false;
    }
}

function buildMinimalPackageJson(): string {
    return `${JSON.stringify({
        dependencies: { [PLUGIN_PACKAGE]: PLUGIN_PACKAGE_VERSION }
    }, null, 2)}\n`;
}

/**
 * Ensure the opencode runtime can resolve `@opencode-ai/plugin` from our
 * isolated config dir. Since opencode 1.14.x the plugin loader is a separate
 * npm package, and `<configDir>/plugins/*.ts` files are only evaluated when
 * that package is resolvable from `<configDir>`. HAPI's per-session
 * OPENCODE_CONFIG_DIR is otherwise an empty directory, so plugin discovery
 * never even attempts to load hapi-hook.ts.
 *
 * Writing a minimal `package.json` declaring the dependency is enough:
 * opencode itself materializes `node_modules` and `package-lock.json` on
 * the next launch (the same install path `opencode plugin install`
 * follows). No symlinks, no install spawn, no cross-platform branches —
 * just a one-line dependency declaration.
 *
 * Guards against three failure modes:
 *   - **Non-managed dir**: when the caller pointed OPENCODE_CONFIG_DIR at a
 *     directory outside `happyHomeDir` (e.g. the user's global opencode
 *     config) we leave it alone — that filesystem is not ours to mutate.
 *   - **Existing package.json missing our dep**: parse it and only short-
 *     circuit when `@opencode-ai/plugin` is already declared. Otherwise
 *     overwrite the placeholder so plugin discovery actually works.
 *   - **Write failure**: log and continue; the scanner channel restored in
 *     upstream #589 still carries messages, so a non-writable cfg dir is
 *     degraded but not fatal.
 */
function ensurePluginRuntime(rootPath: string): void {
    if (!isHapiManagedDir(rootPath)) {
        logger.debug(`[opencode-hook] Skipping plugin runtime materialization for non-HAPI dir: ${rootPath}`);
        return;
    }

    const packageJsonPath = join(rootPath, PACKAGE_JSON_FILENAME);
    if (existsSync(packageJsonPath)) {
        if (hasDeclaredPluginPackage(packageJsonPath)) {
            // Existing file already declares the plugin (likely opencode-
            // installed with a matching lock file). Leave it untouched.
            return;
        }
        logger.debug(`[opencode-hook] package.json exists at ${packageJsonPath} but does not declare ${PLUGIN_PACKAGE}; overwriting placeholder.`);
    }

    try {
        writeFileSync(packageJsonPath, buildMinimalPackageJson(), 'utf-8');
    } catch (error) {
        logger.warn(`[opencode-hook] Failed to materialize ${packageJsonPath}; the hook plugin channel may stay inert. Storage scanner remains as fallback. Error: ${(error as Error).message}`);
    }
}

export function ensureOpencodeHookPlugin(rootPath: string, hookUrl: string, token: string): string {
    const pluginDir = resolvePluginDir(rootPath);
    mkdirSync(pluginDir, { recursive: true });
    ensurePluginRuntime(rootPath);

    const pluginPath = join(pluginDir, PLUGIN_FILENAME);
    const nextSource = buildPluginSource(hookUrl, token);

    try {
        const current = readFileSync(pluginPath, 'utf-8');
        if (current === nextSource) {
            return pluginPath;
        }
    } catch {
        // Ignore missing or unreadable file.
    }

    writeFileSync(pluginPath, nextSource, 'utf-8');
    return pluginPath;
}
